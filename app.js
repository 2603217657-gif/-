function formatTime(seconds) {
  const safe = Number.isFinite(seconds) ? Math.max(0, Math.floor(seconds)) : 0;
  return `${Math.floor(safe / 60)}:${String(safe % 60).padStart(2, "0")}`;
}

function durationOf(track = tracks[currentTrack]) {
  return Number.isFinite(audio.duration) && audio.duration > 0 ? audio.duration : track.durationFallback;
}

function setupAudioGraph() {
  if (audioContext) return;
  audioContext = new AudioContext();
  analyser = audioContext.createAnalyser();
  analyser.fftSize = 256;
  analyser.smoothingTimeConstant = 0.78;
  dataArray = new Uint8Array(analyser.frequencyBinCount);
  sourceNode = audioContext.createMediaElementSource(audio);
  sourceNode.connect(analyser);
  analyser.connect(audioContext.destination);
  canAnalyze = true;
}

function renderLyrics() {
  const track = tracks[currentTrack];
  const lines = track.lyrics
    .map((line, index) => `<p class="lyric-line" data-index="${index}">${line.text}</p>`)
    .join("");
  els.lyricsWindow.innerHTML = `<div class="lyrics-track">${lines}</div>`;
  activeLyric = -1;
}

function updateLyric(position) {
  const track = tracks[currentTrack];
  if (!track.lyrics.length) return;
  let nextActive = 0;
  for (let i = 0; i < track.lyrics.length; i += 1) {
    if (position >= track.lyrics[i].time) nextActive = i;
  }
  if (nextActive === activeLyric) return;
  activeLyric = nextActive;
  const lyricTrack = els.lyricsWindow.querySelector(".lyrics-track");
  const lines = [...els.lyricsWindow.querySelectorAll(".lyric-line")];
  lines.forEach((line, index) => line.classList.toggle("active", index === activeLyric));
  const offset = Math.max(0, activeLyric * 58 - els.lyricsWindow.clientHeight / 2 + 40);
  lyricTrack.style.transform = `translateY(${-offset}px)`;
}

function applyColors() {
  const track = tracks[currentTrack];
  document.documentElement.style.setProperty("--accent", track.colors[(0 + themeShift) % track.colors.length]);
  document.documentElement.style.setProperty("--accent-2", track.colors[(1 + themeShift) % track.colors.length]);
  document.documentElement.style.setProperty("--bg-a", track.colors[2]);
  document.documentElement.style.setProperty("--bg-b", track.colors[3]);
  document.documentElement.style.setProperty("--bg-c", track.colors[1]);
}

function applyTrack(index) {
  const track = tracks[index];
  currentTrack = index;
  activeLyric = -1;
  audio.src = encodeURI(track.src);
  audio.load();
  els.title.textContent = track.title;
  els.artist.textContent = track.artist;
  els.bpm.textContent = track.bpm;
  els.mood.textContent = track.mood;
  els.current.textContent = "0:00";
  els.duration.textContent = formatTime(track.durationFallback);
  els.seek.value = 0;
  els.albumCover.style.setProperty("--cover-image", `url("${track.cover}")`);
  applyColors();
  renderLyrics();
  renderPlaylist();
}

function renderPlaylist() {
  els.trackCount.textContent = `${tracks.length} 首`;
  els.playlist.innerHTML = tracks
    .map((track, index) => `
      <button class="playlist-item ${index === currentTrack ? "active" : ""}" type="button" data-index="${index}">
        <span class="playlist-art" style="--item-a:${track.colors[0]};--item-b:${track.colors[1]};--item-cover:url('${track.cover}')"></span>
        <span class="playlist-copy">
          <strong>${track.title}</strong>
          <span>${track.artist}</span>
        </span>
        <span class="playlist-time">${formatTime(track.durationFallback)}</span>
      </button>
    `)
    .join("");
}

async function togglePlay() {
  if (!audioContext) setupAudioGraph();
  if (audioContext.state === "suspended") await audioContext.resume();
  if (audio.paused) {
    try {
      await audio.play();
      els.body.classList.add("is-playing");
      els.playIcon.textContent = "Ⅱ";
      draw();
    } catch {
      showPlaybackNotice();
    }
  } else {
    audio.pause();
  }
}

function showPlaybackNotice() {
  els.mood.textContent = "音频加载失败";
  els.lyricsWindow.insertAdjacentHTML(
    "afterbegin",
    `<p class="lyric-line active">当前音频没有成功播放，请确认文件路径可访问，或刷新页面后再试。</p>`
  );
}

function changeTrack(index, autoplay = !audio.paused) {
  audio.pause();
  applyTrack((index + tracks.length) % tracks.length);
  if (autoplay) togglePlay();
}

function resizeCanvases() {
  const ratio = window.devicePixelRatio || 1;
  els.wave.width = Math.floor(window.innerWidth * ratio);
  els.wave.height = Math.floor(window.innerHeight * ratio);
  waveCtx.setTransform(ratio, 0, 0, ratio, 0, 0);
  const box = els.spectrum.getBoundingClientRect();
  els.spectrum.width = Math.floor(box.width * ratio);
  els.spectrum.height = Math.floor(box.height * ratio);
  spectrumCtx.setTransform(ratio, 0, 0, ratio, 0, 0);
}

function drawSpectrum(energy) {
  const width = els.spectrum.clientWidth;
  const height = els.spectrum.clientHeight;
  spectrumCtx.clearRect(0, 0, width, height);
  const bars = 54;
  const gap = 4;
  const barWidth = width / bars - gap;
  for (let i = 0; i < bars; i += 1) {
    const value = dataArray ? dataArray[Math.floor((i * dataArray.length) / bars)] / 255 : energy;
    const barHeight = Math.max(8, value * height * 0.92 + energy * 12);
    const x = i * (barWidth + gap);
    const y = height - barHeight;
    const gradient = spectrumCtx.createLinearGradient(0, y, 0, height);
    gradient.addColorStop(0, getComputedStyle(document.documentElement).getPropertyValue("--accent"));
    gradient.addColorStop(1, "rgba(255,255,255,0.08)");
    spectrumCtx.fillStyle = gradient;
    spectrumCtx.fillRect(x, y, barWidth, barHeight);
  }
}

function drawWavefield(energy) {
  const width = window.innerWidth;
  const height = window.innerHeight;
  const accent = getComputedStyle(document.documentElement).getPropertyValue("--accent");
  waveCtx.clearRect(0, 0, width, height);
  waveCtx.lineWidth = 1.5 + energy * 3;
  for (let line = 0; line < 5; line += 1) {
    waveCtx.beginPath();
    waveCtx.strokeStyle = line % 2 ? "rgba(255,255,255,0.18)" : accent;
    waveCtx.globalAlpha = 0.22 + energy * 0.28;
    const base = height * (0.2 + line * 0.16);
    for (let x = 0; x <= width; x += 8) {
      const t = performance.now() / 900 + line * 1.7;
      const y = base + Math.sin(x / (80 - energy * 36) + t) * (18 + energy * 56);
      if (x === 0) waveCtx.moveTo(x, y);
      else waveCtx.lineTo(x, y);
    }
    waveCtx.stroke();
  }
  waveCtx.globalAlpha = 1;
}

function draw() {
  if (canAnalyze && analyser) analyser.getByteFrequencyData(dataArray);
  const energy = dataArray ? dataArray.reduce((sum, value) => sum + value, 0) / dataArray.length / 255 : 0.18;
  document.documentElement.style.setProperty("--energy", energy.toFixed(3));
  drawSpectrum(energy);
  drawWavefield(energy);

  const duration = durationOf();
  els.current.textContent = formatTime(audio.currentTime);
  els.duration.textContent = formatTime(duration);
  els.seek.value = duration ? Math.min(100, (audio.currentTime / duration) * 100) : 0;
  updateLyric(audio.currentTime);

  if (!audio.paused) rafId = requestAnimationFrame(draw);
}

